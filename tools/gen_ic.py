"""Regenerates ui/kit/Ic.java with one constant per icon in ui/icon/IconData.java."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "app", "src", "main", "java", "com", "disgusty", "foxtalgia", "ui")
data = open(os.path.join(SRC, "icon", "IconData.java"), encoding="utf-8").read()
names = re.findall(r"public static final String (M1_\w+) =", data)
have = set(re.findall(r"public static final String (\w+) =", data))
lines = [
    "package com.disgusty.foxtalgia.ui.kit;",
    "",
    "import com.disgusty.foxtalgia.ui.icon.IconData;",
    "",
    "/** Icon glyphs: Material Icons (2014, used by Classic/Holo/Material 1) and Material Symbols (Material 3).",
    " * GENERATED by tools/gen_ic.py from IconData - do not edit by hand. */",
    "public final class Ic {",
    "    public final String m1;",
    "    public final String m3;",
    "    public final String m3Filled;",
    "",
    "    private Ic(String m1, String m3, String m3Filled) {",
    "        this.m1 = m1;",
    "        this.m3 = m3;",
    "        this.m3Filled = m3Filled;",
    "    }",
    "",
]
for m1 in names:
    n = m1[3:]
    m3 = "M3_" + n if "M3_" + n in have else m1
    m3f = "M3_" + n + "_FILLED" if "M3_" + n + "_FILLED" in have else m3
    lines.append("    public static final Ic %s = new Ic(IconData.%s, IconData.%s, IconData.%s);" % (n, m1, m3, m3f))
lines.append("    public static final Ic PRIVATE = new Ic(com.disgusty.foxtalgia.ui.icon.IconExtra.PRIVATE, com.disgusty.foxtalgia.ui.icon.IconExtra.PRIVATE, com.disgusty.foxtalgia.ui.icon.IconExtra.PRIVATE);")
lines.append("}")
open(os.path.join(SRC, "kit", "Ic.java"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(len(names), "icons")
